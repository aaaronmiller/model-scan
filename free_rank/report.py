"""Write the ranking, the per-model breakdown and the L6 route table as JSON and Markdown."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

from . import CONFIG, load_config

CFG = load_config()


def _order(models):
    placed = sorted((m for m in models if m.tier is not None), key=lambda m: (m.tier, -m.score))
    unplaced_chat = sorted((m for m in models if m.tier is None and m.score is not None), key=lambda m: m.label.lower())
    others = sorted((m for m in models if m.score is None), key=lambda m: (m.kind, m.label.lower()))
    return placed, unplaced_chat, others


def selectors(route) -> dict:
    spec = CFG["catalogues"][route.gateway]["selectors"]
    out = {k: v.format(id=route.route_id) for k, v in spec.items()}
    gw_prefix = spec.get("omp", "").split("/", 1)[0]
    out["omp_provider_configured"] = gw_prefix in CFG["omp_configured_providers"]
    return out


def _model_record(m, rank_no):
    return {
        "rank": rank_no, "tier": m.tier, "name": m.label, "model_key": m.key,
        "score": None if m.score is None else round(m.score, 4),
        "share_of_top": None if m.tier is None else round(getattr(m, "score_of_top", 0.0), 4),
        "evidence": round(m.evidence, 3),
        "family_scores": getattr(m, "family_scores", None),
        "context_component": getattr(m, "context_component", None),
        "context_tokens": m.context, "tools": m.tools, "kind": m.kind,
        "limit_tags": m.tags, "reason": m.reason or None,
        "routes": [{"gateway": r.gateway, "route_id": r.route_id, "name": r.name, **selectors(r)} for r in m.routes],
        "breakdown": m.breakdown,
    }


def build_records(result: dict) -> dict:
    placed, unplaced, others = _order(result["models"])
    cfg_hash = hashlib.sha256(Path(CONFIG).read_bytes()).hexdigest()[:12]
    manifest = json.loads((Path(result["folder"]) / "manifest.json").read_text())
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "snapshot": str(result["folder"]),
        "snapshot_sources": {k: {"url": v["url"], "fetched_at": v["fetched_at"], "status": v["status"],
                                 "sha256": v["sha256"]} for k, v in manifest.items()},
        "config_sha256_12": cfg_hash,
        "scoring": {k: v for k, v in CFG["scoring"].items() if not k.startswith("_")},
        "benchmark_weights": {k: {"family": v["family"], "weight": v["weight"]} for k, v in CFG["benchmarks"].items()},
        "tiers": CFG["tiers"],
        "notes": result["notes"],
        "ranked": [_model_record(m, i + 1) for i, m in enumerate(placed)],
        "unplaced": [_model_record(m, None) for m in unplaced],
        "not_ranked": [_model_record(m, None) for m in others],
    }


def _tags_short(tags: dict) -> str:
    return ", ".join(sorted(tags)) or "none"


def ranking_markdown(rec: dict) -> str:
    sc = rec["scoring"]
    lines = [
        "---", "title: Free model ranking by formula", f"date: {rec['generated_at'][:10]}",
        f"snapshot: {Path(rec['snapshot']).name}", f"config: free_rank/config.json sha256 {rec['config_sha256_12']}", "---", "",
        "# Free model ranking by formula", "",
        "Generated by `python3 -m free_rank` from the snapshot named above. Every number comes from a benchmark",
        "source; no model is placed by name. Limit tags are reported and never scored.", "",
        "## Formula", "",
        f"- Per benchmark: independent results win (best configuration per source, median across sources);"
        f" publisher-only values are multiplied by {sc['publisher_discount']} and count {sc['publisher_confidence']} of their weight.",
        f"- Normalisation: {sc['normalisation']} over the ranked pool. Each family's weighted mean is shrunk toward"
        f" {sc['shrinkage_prior']} by {sc['shrinkage_weight']} units of pseudo-evidence, so missing benchmarks are not zeros.",
        f"- Families mixed as {json.dumps(sc.get('family_weights'))}; context adds up to {sc['context_bonus_weight']}"
        f" on a log scale from {sc['context_floor_tokens']} to {sc['context_full_tokens']} tokens.",
        "- Tiers: share of the top score, minimum evidence and tool support, from `config.json`.", "",
    ]
    if rec["notes"]:
        lines += ["## Run notes", ""] + [f"- {n}" for n in rec["notes"]] + [""]
    tier = None
    for m in rec["ranked"]:
        if m["tier"] != tier:
            tier = m["tier"]
            lines += [f"## Tier {tier}", "", "| # | Model | Score | Share of top | Evidence | Context | Limit tags | Routes |",
                      "|---|---|---|---|---|---|---|---|"]
        routes = "<br>".join(f"`{r['gateway']}` `{r['route_id']}`" for r in m["routes"])
        lines.append(f"| {m['rank']} | {m['name']} | {m['score']:.3f} | {m['share_of_top']:.2f} | {m['evidence']:.2f} |"
                     f" {m['context_tokens'] or '?'} | {_tags_short(m['limit_tags'])} | {routes} |")
        if m is rec["ranked"][-1] or rec["ranked"][rec["ranked"].index(m) + 1]["tier"] != tier:
            lines.append("")
    lines += ["## Unplaced (no matched benchmark evidence)", ""]
    for m in rec["unplaced"]:
        lines.append(f"- {m['name']}: " + ", ".join(f"`{r['gateway']}` `{r['route_id']}`" for r in m["routes"]))
    lines += ["", "## Not ranked", ""]
    for m in rec["not_ranked"]:
        lines.append(f"- {m['name']} ({m['reason']}): " + ", ".join(f"`{r['route_id']}`" for r in m["routes"]))
    lines += ["", "## Score breakdown", ""]
    for m in rec["ranked"]:
        fam = m["family_scores"] or {}
        lines += [f"### {m['rank']}. {m['name']}", "",
                  f"Score {m['score']:.4f} = family mix {json.dumps(fam)} + context {m['context_component']}. Evidence {m['evidence']:.2f}.", "",
                  "| Benchmark | Family | Raw | Independent | Normalised | Weight x confidence | Sources |",
                  "|---|---|---|---|---|---|---|"]
        for b in m["breakdown"]:
            srcs = "; ".join(f"{s['value']:.2f} {s['host']} ({s['setting'][:60]})" for s in b["sources"])
            lines.append(f"| {b['benchmark']} | {b['family']} | {b['raw']} | {'yes' if b['independent'] else 'no'} |"
                         f" {b['normalised']} | {b['weight']} x {b['confidence']} | {srcs} |")
        lines.append("")
    return "\n".join(lines)


def routes_records(rec: dict) -> list[dict]:
    rows = []
    for m in rec["ranked"]:
        for r in m["routes"]:
            rows.append({"rank": m["rank"], "tier": m["tier"], "model": m["name"], "gateway": r["gateway"],
                         "route_id": r["route_id"], "omp": r.get("omp"), "omp_provider_configured": r["omp_provider_configured"],
                         "opencode": r.get("opencode"), "kilo": r.get("kilo"), "limit_tags": sorted(m["limit_tags"])})
    return rows


def routes_markdown(rows: list[dict], generated: str) -> str:
    lines = ["---", "title: Free model routes for harness fallback chains", f"date: {generated[:10]}", "---", "",
             "# Free model routes for harness fallback chains", "",
             "One row per free route of every ranked model, in rank order. `omp` is the provider/model selector",
             "for `~/.omp/agent/config.yml` fallbackChains; a route whose provider is not configured in omp is",
             "marked. `opencode` uses the `opencode/` (Zen) or `opencode-go/` prefix. `kilo` is the Kilo gateway id.", "",
             "| Rank | Tier | Model | Gateway | omp selector | OpenCode | Kilo | Limit tags |",
             "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        omp = f"`{r['omp']}`" + ("" if r["omp_provider_configured"] else " (provider not configured in omp)")
        lines.append(f"| {r['rank']} | {r['tier']} | {r['model']} | {r['gateway']} | {omp} |"
                     f" {'`' + r['opencode'] + '`' if r['opencode'] else '-'} | {'`' + r['kilo'] + '`' if r['kilo'] else '-'} |"
                     f" {', '.join(r['limit_tags']) or 'none'} |")
    return "\n".join(lines) + "\n"


def agreement_markdown(c: dict, rec: dict) -> str:
    lines = ["---", "title: Formula agreement with the reference tiers", f"date: {rec['generated_at'][:10]}", "---", "",
             "# Formula agreement with the reference tiers", "",
             f"- Kendall tau-b over Tier 1 and 2 order: **{c['kendall_tau']:.3f}** ({c['models_compared']} reference models the formula places)",
             f"- Spearman rho over the same: **{c['spearman_rho']:.3f}**",
             f"- Tier agreement over all reference entries: **{c['tier_agreement']}**",
             f"- Same Tier 1 set: **{c['tier1_same_set']}** (missing {c['tier1_missing'] or 'none'}, extra {c['tier1_extra'] or 'none'})", "",
             "| Reference order (T1, T2) | Formula order |", "|---|---|"]
    ref, form = c["reference_order_t1_t2"], c["formula_order_t1_t2"]
    for i in range(max(len(ref), len(form))):
        lines.append(f"| {ref[i] if i < len(ref) else ''} | {form[i] if i < len(form) else ''} |")
    lines += ["", "## Disagreements", "", "| Model | Reference tier | Formula tier | Score | Evidence | Reason |", "|---|---|---|---|---|---|"]
    for d in c["disagreements"]:
        lines.append(f"| {d['name']} | {d['ref_tier']} | {d['tier']} | {'' if d['score'] is None else round(d['score'], 3)} |"
                     f" {'' if d['evidence'] is None else round(d['evidence'], 2)} | {d['reason'] or ''} |")
    return "\n".join(lines) + "\n"
